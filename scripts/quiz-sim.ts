/**
 * The full Bangkok Type quiz balance run: 50,000 simulated quiz-takers.
 *
 *   npx tsx scripts/quiz-sim.ts                 50,000 sessions, prints the numbers
 *   npx tsx scripts/quiz-sim.ts 5000            a quicker run
 *   npx tsx scripts/quiz-sim.ts 50000 --write   also rewrites design/reference/quiz-balance.md
 *
 * No database, no network: it only runs the quiz code (test/quiz-sim.ts).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { simulate, type SimReport } from "../test/quiz-sim";
import { TYPE_CODES } from "../src/vibe/scenarios";
import { ARCHETYPES } from "../src/vibe/archetypes";

const n = Number(process.argv.find((a) => /^\d+$/.test(a)) ?? 50_000);
const write = process.argv.includes("--write");

const started = Date.now();
const r = simulate(n);
const secs = ((Date.now() - started) / 1000).toFixed(1);

const pct = (x: number, d = 1) => `${(100 * x).toFixed(d)}%`;
const fmt = (x: number) => x.toLocaleString("en-US");

function report(r: SimReport): string {
  const exp = r.sessions / 16;
  const rows = TYPE_CODES.map((c) => {
    const name = ARCHETYPES[c]?.name?.en ?? c;
    return `| ${c} | ${name} | ${fmt(r.random.counts[c])} | ${pct(r.random.counts[c] / r.sessions)} | ${pct((r.random.counts[c] - exp) / exp)} | ${pct(r.persona.recovered[c])} |`;
  }).join("\n");
  const letters = ([["B", "C"], ["D", "F"], ["M", "S"], ["N", "H"]] as const)
    .map(([a, b]) => `${a} ${pct(r.random.letterShare[a])} / ${b} ${pct(r.random.letterShare[b])}`)
    .join(" · ");
  return `## Run: ${fmt(r.sessions)} sessions (${secs} s)

**Bank:** ${r.scenariosInBank} scenarios, ${r.scenariosUsed} used across the run. Questions per session: ${r.questionsPerSession.min} to ${r.questionsPerSession.max}.
**Curated sets:** ${fmt(r.distinctSessions)} distinct question lists (3 segments, with the seasonal slot by month).

### Structure
- Questions with a letter not split half and half: **${r.structure.unbalancedQuestions}**
- 20-question sessions where a type was offered outside 7 or 8 times: **${r.structure.offerOutOfRange}**
- Option positions: busiest type-and-position cell vs the quietest, **${r.structure.positionSpread.toFixed(2)}x**

### People with no preference (random answers)
Letter split: ${letters}
Largest gap from an even 6.25% per type: **${pct(r.random.maxDeviation)}**

| Code | Type | Results | Share | vs even | Real person (p=${r.persona.p}) gets it back |
|---|---|---|---|---|---|
${rows}

### People who know who they are
- Real person, picks their best fit ${pct(r.persona.p, 0)} of the time: **${pct(r.persona.overall)}** get their own type, **${pct(r.persona.withinRange)}** see it in the headline range; twin agreement ${pct(r.persona.meanConsistency)}
- Perfectly consistent person: **${pct(r.perfect.recovered)}** get their own type; twin agreement ${pct(r.perfect.meanConsistency)}
- Noisy person (best fit ${pct(r.noisy.p, 0)} of the time): **${pct(r.noisy.overall)}** get their own type
- Contradicts themselves halfway: **${pct(r.contradictory.confident)}** still come out fully confident; on average ${r.contradictory.meanUnsureLetters.toFixed(2)} of 4 letters marked unsure
`;
}

const out = report(r);
console.log(out);
if (write) {
  const doc = `# Bangkok Type quiz balance

*Generated by \`npx tsx scripts/quiz-sim.ts ${n} --write\`. Rerun it after any change to the question bank, the generator or the scoring; \`npm test\` runs a smaller sample (test/quiz-balance.test.ts) every time.*

How it works: each simulated session is built and scored exactly as the live quiz does (generateSession, scoreSession, typeOf), with the same mix of profiles (no personalisation, a home district, friends-only). Each session is answered by five kinds of people: no preference (random), a real person of a known type who picks their best fit ${pct(r.persona.p, 0)} of the time and a neighbouring answer otherwise, a perfectly consistent person, a noisy person, and someone who contradicts themselves halfway.

${out}`;
  // Keep the hand-written findings below the numbers across reruns.
  const path = "design/reference/quiz-balance.md";
  const old = existsSync(path) ? readFileSync(path, "utf8") : "";
  const findings = old.includes("\n## Findings") ? old.slice(old.indexOf("\n## Findings")) : "";
  writeFileSync(path, doc + findings);
  console.log("wrote design/reference/quiz-balance.md");
}
