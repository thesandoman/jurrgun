/**
 * Turns drizzle/*.sql into src/migrations.ts so the deployed app can apply
 * them once through the guarded setup route (src/routes/setup.ts). Workers
 * have no filesystem, so the SQL has to be bundled as code.
 *
 *   npm run db:generate && npm run migrations
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "drizzle";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const migrations = files.map((file) => ({
  id: file.replace(/\.sql$/, ""),
  statements: readFileSync(join(dir, file), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    // btree is the default everywhere; CockroachDB (the deployed database) is
    // stricter about the explicit USING clause than Postgres, so drop it.
    .map((s) => s.replace(/ USING btree/gi, ""))
    .filter(Boolean),
}));
const out = `// GENERATED by scripts/build-migrations.mjs from drizzle/*.sql — do not edit.\nexport const MIGRATIONS: { id: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync("src/migrations.ts", out);
console.log(`wrote src/migrations.ts (${migrations.length} migration(s))`);
