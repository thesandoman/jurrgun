/**
 * Turns the open universities list into src/content/universities.generated.ts
 * (name + country only), so the Worker can search it without a database.
 *
 * Source: github.com/Hipo/university-domains-list (MIT licence),
 * file world_universities_and_domains.json. Download it, then:
 *
 *   node scripts/build-universities.mjs path/to/world_universities_and_domains.json
 *
 * Thai additions and Thai-language names live in src/content/universities.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/build-universities.mjs <world_universities_and_domains.json>");
const raw = JSON.parse(readFileSync(src, "utf8"));
const seen = new Set();
const rows = [];
for (const u of raw) {
  const name = String(u.name ?? "").replace(/\s+/g, " ").trim();
  const cc = String(u.alpha_two_code ?? "").toUpperCase();
  if (!name || !/^[A-Z]{2}$/.test(cc)) continue;
  const key = `${cc}|${name.toLowerCase()}`;
  if (seen.has(key)) continue;
  seen.add(key);
  rows.push([name, cc]);
}
rows.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
const out = `// GENERATED by scripts/build-universities.mjs — do not edit.
// From github.com/Hipo/university-domains-list (MIT licence). ${rows.length} universities: [name, ISO country code].
export const UNIVERSITY_ROWS: [string, string][] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL("../src/content/universities.generated.ts", import.meta.url), out);
console.log(`wrote src/content/universities.generated.ts (${rows.length} universities, ${Math.round(out.length / 1024)} KB)`);
