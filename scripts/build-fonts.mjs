/**
 * Bundles the brand fonts in design/fonts/*.woff2 into
 * src/vendor/fonts.generated.ts, so the Worker serves them itself at
 * /fonts/<name>.<hash>.woff2 (same origin, cached hard). They don't go through
 * design/assets/: that route redirects to storage on another origin, and
 * cross-origin fonts need CORS headers the storage doesn't send.
 *
 *   npm run fonts
 *
 * The files are subset WOFF2 made from the BMA type system (see
 * design/fonts/README.md for where they came from and how to remake them).
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../design/fonts/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".woff2")).sort();
const entries = files.map((f) => {
  const buf = readFileSync(new URL(f, dir));
  const name = f.replace(/\.woff2$/, "");
  const hash = createHash("sha256").update(buf).digest("hex").slice(0, 10);
  return `  ${JSON.stringify(name)}: { hash: ${JSON.stringify(hash)}, b64: ${JSON.stringify(buf.toString("base64"))} },`;
});
const out = `// GENERATED by scripts/build-fonts.mjs from design/fonts/ — do not edit.
export const FONT_FILES = {
${entries.join("\n")}
} as const;
`;
writeFileSync(new URL("../src/vendor/fonts.generated.ts", import.meta.url), out);
console.log(`wrote src/vendor/fonts.generated.ts (${files.length} fonts)`);
